import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
const ts=createRequire(new URL('../apps/web/package.json',import.meta.url))('typescript');
const source=await readFile(new URL('../apps/web/src/lib/graph.ts',import.meta.url),'utf8');
const {outputText}=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}});
const {edgeKey,edgeSubject,neighborhood,sortedEvents,clipToCard,edgeCurve,isDrag}=await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const nodes=[{id:'p',type:'person',name:'甲'},{id:'q',type:'person',name:'乙'},{id:'late',type:'event',title:'后',start_year:923},{id:'early',type:'event',title:'先',start_year:907},{id:'same',type:'event',title:'同年',start_year:907},{id:'unknown',type:'event',title:'待考'}];
const edges=[{id:'1',source:'p',target:'q',type:'父亲',subject_table:'person_relationship'},{id:'1',source:'q',target:'early',type:'参与',subject_table:'person_event'}];
const data={center:nodes[0],nodes,edges};
assert.deepEqual([...neighborhood(data,'p',1)].sort(),['p','q']);
assert.deepEqual([...neighborhood(data,'p',2)].sort(),['early','p','q']);
assert.notEqual(edgeKey(edges[0]),edgeKey(edges[1]),'Different relationship tables may have the same ID');
assert.equal(edgeSubject(edges[1],nodes),'person_event');
assert.equal(edgeSubject({...edges[0],subject_table:undefined},nodes),'person_relationship');
assert.deepEqual(sortedEvents(nodes).map(n=>n.id),['early','same','late','unknown']);
assert.equal(nodes[2].id,'late','Sorting must not reorder source data');
assert.equal(isDrag({x:0,y:0},{x:3,y:4}),false,'Small hand movement remains a click');
assert.equal(isDrag({x:0,y:0},{x:6,y:0}),true,'Dragging must suppress selection');
assert.deepEqual(clipToCard({x:0,y:0},{x:300,y:0}),{x:86,y:0});
assert.notEqual(edgeCurve({x:0,y:0},{x:300,y:0},40).path,edgeCurve({x:0,y:0},{x:300,y:0},-40).path);
assert.ok(!edgeCurve({x:1,y:2},{x:1,y:2}).path.includes('NaN'));
console.log('Graph tests passed: drag threshold, relation identities, neighborhood depth, chronological stability, card geometry.');
