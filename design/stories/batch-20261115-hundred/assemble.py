"""Assemble only reviewed story sheets into the existing catalog contract."""
import argparse,hashlib,json
from pathlib import Path
from PIL import Image,ImageStat

BASE=Path(__file__).resolve().parent
ROOT=BASE.parents[2]
def write(p,d):p.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n')
def edges(im,n,axis):
    w,h=im.size;length=(w,h)[axis];values=[0]
    for i in range(1,n):
        center=round(length*i/n);radius=min(22,round(length/n*.06))
        def variance(at):
            box=(at,8,at+1,h-8) if axis==0 else (8,at,w-8,at+1)
            return sum(ImageStat.Stat(im.crop(box)).stddev)
        values.append(min(range(center-radius,center+radius+1),key=variance))
    return values+[length]
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--merge',action='store_true');args=parser.parse_args()
    scripts=json.loads((BASE/'scripts.json').read_text())['stories']
    ids={x['slug']:x for x in json.loads((BASE/'identities.json').read_text())}
    proofs={x['slug']:x for x in json.loads((BASE/'existing-ingestion.json').read_text())}
    reviews=json.loads((BASE/'image-reviews.json').read_text())
    draft=[]
    for s in scripts:
        review=reviews.get(s['slug'])
        if not review or review['status']!='approved':continue
        file=BASE/s['slug']/review.get('file','atlas-v1.png')
        sha=hashlib.sha256(file.read_bytes()).hexdigest();im=Image.open(file).convert('RGB');w,h=im.size
        n=len(s['panels']);xs=edges(im,2,0);ys=edges(im,review.get('gridRows',n//2),1)
        panels=[]
        for i,p in enumerate(s['panels']):
            source_index=review.get('selectedCells',list(range(n)))[i]
            col=source_index%2;row=source_index//2;inset=8
            crop=dict(x=xs[col]+inset,y=ys[row]+inset,width=xs[col+1]-xs[col]-2*inset,height=ys[row+1]-ys[row]-2*inset)
            panels.append({**{k:p[k] for k in ['number','title','caption','alt']},'crop':crop})
        people=[{k:v for k,v in p.items() if k in ['name','id','aliases']} for p in ids[s['slug']]['people']]
        first=s['sourceParagraphs'][0]
        links=[dict(label='读原文',url=f'/library/shiji/{first["section_id"]}?paragraph={first["id"]}#paragraph-{first["id"]}')]
        story=dict(slug=s['slug'],title=s['title'],description=s['introduction']['text'].split('。')[0]+'。',
            readingMinutes=3 if n>=8 else 2,introduction=s['introduction'],afterword=s['afterword'],
            image=dict(url=f'/api/v1/media/images/{sha}.png',width=w,height=h,sha256=sha),panels=panels,people=people,sourceLinks=links)
        draft.append(story)
        paragraphs=s['sourceParagraphs'];excerpt='\n\n'.join(p['text'] for p in paragraphs)
        audit=dict(slug=s['slug'],status='approved',reviewDate='2026-11-15',reviewer='Codex source, script and image editorial review',
            authorization='用户要求从已有录入历史中整理故事并扩展至100篇，特别重视后记和寓意；沿用既定画风。本轮编辑审图不代称用户逐幅确认。',
            kind=s['kind'],panelCount=n,imageSha256=sha,
            source=dict(book=s['afterword']['sourceNote'],locator='local:'+';'.join(p['id'] for p in paragraphs),
                excerpt=excerpt,excerptSha256=hashlib.sha256(excerpt.encode()).hexdigest(),
                paragraphs=[dict(id=p['id'],**p['locator']) for p in paragraphs],
                snapshots=[f'design/stories/batch-20261115-hundred/sources/{p["id"]}/source.txt' for p in paragraphs],
                transcriptionNote='从选定TXT逐字导出，保留原件与工作文本哈希和行、字符定位；电子转录不宣称纸本异文全校。'),
            existingIngestion=proofs[s['slug']]['existingIngestion'],panels=s['panels'],
            adaptations=['图下注文与对白为现代白话改写，画中衣色、神态、布景为艺术表现；不冒充原文逐字引语。',
                '后记解释情节与人物处境，寓意为现代阅读理解，不新增人物事件或强定原文未载的年份。',
                '没有可唯一核对的已发布人物时保留姓名，不猜配稳定ID；匿名角色不配真人。']+review.get('sourceNotes',[]),
            unboundPeople=ids[s['slug']]['unboundPeople'],
            imageReview=dict(**review,rowEdges=ys,columnEdges=xs,reviewedPanels=n),
            generation=dict(mode='built-in image_gen',useCase='illustration-story',prompt=review.get('originalPrompt',s['prompt']),
                reference='design/stories/yi-mu-li-xin-v2/images/yi-mu-li-xin-eight-panels-vintage-v2.png',
                corrections=review.get('corrections',[])),
            publicationScope='仅故事目录与公开图片；不写事实库、不推进任何史书账本。')
        write(ROOT/'docs/stories'/f'{s["slug"]}.json',audit)
    write(BASE/'catalog-draft.json',dict(stories=draft))
    if args.merge:
        assert len(draft)==50,'All 50 stories must have completed image review'
        # Derivatives must already be generated by the shared image preparation script.
        catalog=json.loads((BASE/'catalog-draft-with-images.json').read_text())['stories']
        assert [s['slug'] for s in draft]==[s['slug'] for s in catalog]
        for s in catalog:assert s['cover'] and all(p['image'] for p in s['panels'])
        path=ROOT/'apps/web/src/data/stories.json';current=json.loads(path.read_text())
        existing={s['slug'] for s in current['stories']}
        assert not existing.intersection(s['slug'] for s in catalog),'Do not overwrite existing stories'
        assert len(current['stories'])==50
        current['stories']+=catalog;assert len(current['stories'])==100
        write(path,current)
    print('Assembled',len(draft),'reviewed stories')
if __name__=='__main__':main()
