"""Produce audited corrected copies using local PDFs and paired watermark rules.

Original files and published evidence are immutable. No network or publication.
PDF cache rows: {pdf_page: int, text: str}; generated by pypdf from local PDFs.
"""
import argparse
import bisect
from collections import Counter
from difflib import SequenceMatcher
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'resources/originals/twenty-four-histories'
OUT = ROOT / 'resources/derived/corrected-txt'
MODERN = re.compile(r'无产阶级|布哈林|黑格尔|唯物主义|马克思|资本主义|社会主义|辩证法')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def norm(text):
    return re.sub(r'\s', '', text)


def local(path):
    return str(path.relative_to(ROOT))


def verify_replay(manifest):
    """Reject stale overlays or changes missing from the line-level audit."""
    source = ROOT / manifest['source_file']
    target = ROOT / manifest['corrected_file']
    audit = ROOT / manifest['edits_file']
    assert sha(source) == manifest['source_sha256']
    assert sha(target) == manifest['corrected_sha256']
    assert sha(audit) == manifest['edits_sha256']
    lines = source.read_bytes().decode(manifest['original_encoding'], errors='surrogateescape').splitlines(keepends=True)
    seen = set()
    for record in audit.read_text().splitlines():
        edit = json.loads(record)
        i = edit['line'] - 1
        assert i not in seen and lines[i] == edit['before']
        seen.add(i)
        assert re.search(r'[\r\n]*$', edit['before'])[0] == re.search(r'[\r\n]*$', edit['after'])[0]
        lines[i] = edit['after']
    assert len(seen) == manifest['changes']
    corrected = target.read_bytes().decode('utf-8')
    assert ''.join(lines) == corrected
    assert not any(0xdc80 <= ord(c) <= 0xdcff for c in corrected)
    return corrected


def pdf_reference(cache, stem):
    path = cache / (stem + '.jsonl')
    text, ends, pages = [], [], []
    size = 0
    title = stem[2:]
    for line in path.open():
        row = json.loads(line)
        body = []
        for i, raw in enumerate(row['text'].splitlines()):
            s = norm(raw)
            if i < 4 and (s == title or re.fullmatch(r'\d+/\d+', s)):
                continue
            body.append(s)
        chunk = ''.join(body)
        text.append(chunk)
        size += len(chunk)
        ends.append(size)
        pages.append(row['pdf_page'])
    pdf = BASE / (stem + '.pdf')
    return {'text': ''.join(text), 'ends': ends, 'pages': pages,
            'source_file': local(pdf), 'source_sha256': sha(pdf),
            'extraction_cache_sha256': sha(path)}


def align(line, ref):
    """Require unique 12-character endpoints and a bounded, similar PDF passage."""
    text = norm(line)
    if len(text) < 30 or '-->' in text:
        return None
    pdf = ref['text']
    candidates = []
    for anchor in [12, 8]:
        left, right = text[:anchor], text[-anchor:]
        start = pdf.find(left)
        attempts = 0
        while start >= 0 and attempts < 20:
            attempts += 1
            finish = pdf.find(right, start + anchor, start + max(2 * len(text), 200))
            if finish >= 0:
                finish += anchor
                replacement = pdf[start:finish]
                ratio = SequenceMatcher(None, text, replacement, autojunk=False).ratio()
                if ratio >= 0.65 and len(replacement) <= len(text) * 1.35:
                    candidates.append((start, finish, replacement, ratio, anchor))
            start = pdf.find(left, start + 1)
        if candidates:
            break
    if not candidates or len({c[2] for c in candidates}) != 1:
        return None
    start, finish, replacement, ratio, anchor = candidates[0]
    first = bisect.bisect_right(ref['ends'], start)
    last = bisect.bisect_right(ref['ends'], finish - 1)
    return replacement, {'source_file': ref['source_file'],
                         'source_sha256': ref['source_sha256'],
                         'pdf_page_start': ref['pages'][first], 'pdf_page_end': ref['pages'][last],
                         'anchor_length': anchor, 'similarity': round(ratio, 5),
                         'excerpt': replacement}


def write_result(source, originals, corrected, edits, unresolved, reference=None):
    folder = OUT / source.stem
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / 'corrected-source.txt'
    text = ''.join(corrected)
    assert not any(0xdc80 <= ord(c) <= 0xdcff for c in text), 'Uncorrected invalid byte'
    target.write_text(text)
    # ASCII JSON preserves surrogateescaped original bytes exactly in audit data.
    audit = folder / 'edits.jsonl'
    audit.write_text(''.join(json.dumps(edit) + '\n' for edit in edits))
    manifest = {'format_version': 'txt-correction-v1', 'source_file': local(source),
                'source_sha256': sha(source), 'original_encoding': 'gb18030',
                'corrected_file': local(target), 'corrected_sha256': sha(target),
                'edits_file': local(audit), 'edits_sha256': sha(audit),
                'changes': len(edits), 'change_types': dict(Counter(e['reason'] for e in edits)),
                'unresolved': unresolved, 'status': 'corrected_reading_copy_requires_source_review',
                'limitations': ['PDF底本未核纸本；仅按仓库本地PDF对照，未声称独立校勘。',
                                '未修正缺少字形映射的私用区字符；原文件及已发布快照未改。']}
    if reference:
        manifest['reference'] = {k: v for k, v in reference.items() if k not in ['text', 'ends', 'pages']}
    (folder / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(source.name, manifest['change_types'], 'unresolved', len(unresolved), flush=True)
    return manifest


def pdf_repairs(source, ref, repair_all=False):
    text = source.read_bytes().decode('gb18030', errors='surrogateescape')
    lines = text.splitlines(keepends=True)
    corrected, edits, unresolved = [], [], []
    for i, original in enumerate(lines, 1):
        line = original.rstrip('\r\n')
        ending = original[len(line):]
        bad = any(0xdc80 <= ord(c) <= 0xdcff for c in line)
        flagged = bool(MODERN.search(line))
        match = align(line, ref) if repair_all or bad else None
        if bad:
            # The local PDFs contain private glyph F8F5 / corrupted text here too.
            # Make decoding usable without pretending to recover the lost glyph.
            new = ''.join(f'〔缺字：原字节{ord(c)-0xdc00:02X}〕' if 0xdc80 <= ord(c) <= 0xdcff else c for c in original)
            edits.append({'line': i, 'before': original, 'after': new,
                          'reason': 'invalid_byte_explicit_missing_glyph',
                          'evidence': '原字节无法严格解码；本地PDF相应处亦含私用字/乱码，不猜字。'})
            corrected.append(new)
            for pos, c in enumerate(line):
                if 0xdc80 <= ord(c) <= 0xdcff:
                    unresolved.append({'line': i, 'char_start': pos, 'kind': 'missing_original_glyph',
                                       'byte': f'{ord(c)-0xdc00:02X}', 'context': ascii(line[max(0,pos-25):pos+30])})
        elif match and norm(line) != match[0]:
            replacement, evidence = match
            changes = [op for op in SequenceMatcher(None, norm(line), replacement, autojunk=False).get_opcodes() if op[0] != 'equal']
            # Restrict this task to extraneous inserted passages. Preserve other
            # differences between editions and PDF extraction for separate review.
            deletions = [op for op in changes if op[0] == 'delete'
                         and len(norm(line)[op[1]:op[2]]) >= 2
                         and re.search(r'[\u3400-\u9fff]', norm(line)[op[1]:op[2]])
                         and not any(0xe000 <= ord(c) <= 0xf8ff for c in norm(line)[op[1]:op[2]])]
            if not deletions:
                corrected.append(original)
                if flagged:
                    unresolved.append({'line': i, 'kind': 'modern_text_requires_comparison', 'original': ascii(line[:300])})
                continue
            # PDF extraction can omit private glyphs. Remove only the attested
            # extra Chinese passages, retaining other original characters.
            repaired = norm(line)
            for _, first, last, _, _ in reversed(deletions):
                repaired = repaired[:first] + repaired[last:]
            # Retain indentation and exact source line count/delimiters.
            indent = line[:len(line) - len(line.lstrip())]
            new = indent + repaired + ending
            edits.append({'line': i, 'before': original, 'after': new,
                          'reason': 'local_pdf_compared_invalid_bytes' if bad else 'local_pdf_compared_text',
                          'evidence': evidence})
            corrected.append(new)
        else:
            corrected.append(original)
            if bad or flagged:
                unresolved.append({'line': i, 'kind': 'invalid_bytes' if bad else 'modern_text',
                                   'original': ascii(line[:300])})
    return write_result(source, lines, corrected, edits, unresolved, ref)


def qing_repairs(source):
    lines = source.read_bytes().decode('gb18030').splitlines(keepends=True)
    corrected, edits, unresolved = [], [], []
    # Individually inspected residual site suffixes; damaged names/layout stay unresolved.
    residual = {
        '清史稿(上)': {18212: '官（官公主府长史陵寝驻防各官各省驻防将军等官提督等官各处驻知',
                      25287: '-623-6232-主', 29482: '纯?淮?皇贵妃世宗诸妃古'},
        '清史稿(下)': {26718: '陈?瘸?荣  芮复传蒋林  阎尧熙王时翔  蓝鼎元古',
                      28920: '刘?Ａ?马秉伦  刘镇宝  罗鸣序斋',
                      35830: '20002000.04.22  尹小林整理主'},
    }[source.stem]
    decoration = re.compile(r'^(?:}|A:visited\s*\{|A:active\s*\{|COLOR:\s*#800500;\s*TEXT-DECORATION:\s*none|J\d+|二十四史系列之一|二十五史系列)$')
    for i, original in enumerate(lines, 1):
        line = original.rstrip('\r\n')
        ending = original[len(line):]
        reason = None
        new = line
        if i in residual:
            assert line == residual[i], 'Manual correction source changed'
            new, reason = line[:-1], 'individually_reviewed_web_watermark'
            if i == 35830:
                new, reason = '2000.04.22  尹小林整理', 'web_credit_duplicate_and_watermark'
            else:
                unresolved.append({'line': i, 'kind': 'damaged_name_or_table_requires_source', 'sample': new})
        elif decoration.fullmatch(line.strip()) or (line and set(line) == {'\x00'}):
            new, reason = '', 'web_style_or_decoration'
        elif not line.startswith((' ', '\t', '\u3000')):
            # Paired evidence: duplicated first two non-whitespace characters AND
            # the site's one-character suffix. Never deduplicate unpaired prose.
            pair = re.fullmatch(r'([^\s]{2})\1(.*)([主知古斋])', line)
            parenthetical = re.fullmatch(r'（([^\s])\1(.*)([主知古斋])', line)
            if pair:
                new, reason = pair[1] + pair[2], 'paired_web_watermark'
            elif parenthetical:
                new, reason = '（' + parenthetical[1] + parenthetical[2], 'paired_parenthetical_web_watermark'
            elif re.search(r'[。！？；”」）][主知古斋]$', line):
                new, reason = line[:-1], 'watermark_suffix_after_punctuation'
            elif line and line[-1] in '主知古斋':
                unresolved.append({'line': i, 'kind': 'unpaired_watermark_candidate', 'sample': line[:180]})
        updated = new + ending
        corrected.append(updated)
        if reason:
            edits.append({'line': i, 'before': original, 'after': updated, 'reason': reason})
    return write_result(source, lines, corrected, edits, unresolved)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pdf-cache', type=Path, required=True)
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    manifests = []
    for name, stem in [('14南史.TXT', '14南史'), ('20宋史.txt', '20宋史'), ('24明史.txt', '24明史')]:
        manifests.append(pdf_repairs(BASE / name, pdf_reference(args.pdf_cache, stem), repair_all=stem == '24明史'))
    for name in ['清史稿(上).txt', '清史稿(下).txt']:
        manifests.append(qing_repairs(BASE / name))
    (OUT / 'catalog.json').write_text(json.dumps(manifests, ensure_ascii=False, indent=2) + '\n')


if __name__ == '__main__':
    main()
