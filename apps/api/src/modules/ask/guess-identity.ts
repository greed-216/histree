export function editorialGuessName(name: string): string {
  return equivalentNames[name] || name;
}
export function guessIdentityVariants(name: string): string[] {
  const identity = editorialGuessName(name);
  return [
    identity,
    ...Object.keys(equivalentNames).filter(
      (n) => equivalentNames[n] === identity,
    ),
  ];
}
